# arithmetic operators

x = 10
y = 5

sum = x+y
diff = x-y
division = x/y
modulus = x%y
power = x**y

print(f"{sum} \n{diff} \n{division} \n{modulus} \n{power}")


# comparision operators

print(x==y)
print(x>=y)
print(x>y)
print(x<y)


# logical operators

print(x>y and x<y) #false
print(x>y or x<y) #true
print(not(x>y)) #false

